const dicts: Record<Lang, Dict> = { ko, en, ja }

export type TFn = (key: MessageKey, vars?: Record<string, string | number>) => string

interface I18nValue {
  lang: Lang
  t: TFn
}

const I18nContext = createContext<I18nValue>({
  lang: 'ko',
  t: (key, vars) => interpolate(ko[key] ?? key, vars),
})

function interpolate(message: string, vars?: Record<string, string | number>): string {
  if (!vars) return message
  let out = message
  for (const [key, value] of Object.entries(vars)) {
    out = out.split(`{${key}}`).join(String(value))
  }
  return out
}

export function I18nProvider({ lang, children }: { lang: Lang; children: ReactNode }) {
  const value = useMemo<I18nValue>(() => {
    const dict = dicts[lang] ?? ko
    const t: TFn = (key, vars) => interpolate(dict[key] ?? ko[key] ?? key, vars)
    return { lang, t }
  }, [lang])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useT(): I18nValue {
  return useContext(I18nContext)
}

